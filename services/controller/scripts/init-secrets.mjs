#!/usr/bin/env node
// Generates the controller's bearer tokens into the git-ignored secrets/ directory.
//
//   node services/controller/scripts/init-secrets.mjs
//
// - Never prints token values and never overwrites an existing file.
// - controller.env holds every token (read by the controller).
// - Each client gets only its own token: the workers' *.controller.env files, and
//   hermes-controller.token (restricted delegator role, mounted read-only into Hermes).
//   The admin token is not handed to any service.
// - Existing installs: add the Hermes token with add-hermes-token.mjs instead.
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const repoRoot = fileURLToPath(new URL('../../../', import.meta.url));
const secretsDir = process.argv[2] ?? join(repoRoot, 'secrets');
const controllerUrl = 'http://controller:3000';

const token = () => randomBytes(32).toString('base64url');
const admin = token();
const claude = token();
const codex = token();
const hermes = token();

const files = {
  'controller.env': [
    '# NestJS Task Controller tokens. Generated by services/controller/scripts/init-secrets.mjs',
    `CONTROLLER_ADMIN_TOKEN=${admin}`,
    `CONTROLLER_CLAUDE_WORKER_TOKEN=${claude}`,
    `CONTROLLER_CODEX_WORKER_TOKEN=${codex}`,
    `CONTROLLER_HERMES_TOKEN=${hermes}`,
  ],
  'hermes-controller.token': [hermes],
  'claude-worker.controller.env': [
    '# Worker access to the task controller, for claude-worker only',
    `CONTROLLER_URL=${controllerUrl}`,
    `CONTROLLER_WORKER_TOKEN=${claude}`,
  ],
  'codex-worker.controller.env': [
    '# Worker access to the task controller, for codex-worker only',
    `CONTROLLER_URL=${controllerUrl}`,
    `CONTROLLER_WORKER_TOKEN=${codex}`,
  ],
};

const existing = Object.keys(files).filter((name) => existsSync(join(secretsDir, name)));
if (existing.length > 0) {
  console.error(`Refusing to overwrite existing secrets: ${existing.join(', ')}`);
  console.error('Delete them first if you really want to rotate all controller tokens.');
  process.exit(1);
}

mkdirSync(secretsDir, { recursive: true });
for (const [name, lines] of Object.entries(files)) {
  // 0600 is honoured on Linux/macOS; on Windows the file inherits the folder ACL.
  writeFileSync(join(secretsDir, name), `${lines.join('\n')}\n`, { mode: 0o600, flag: 'wx' });
  console.log(`created ${join(secretsDir, name)}`);
}
